"""
Evony Dataset Curator
======================
Professional data curation tool with quality scoring, junk detection,
and human review workflow. Does NOT blindly copy - evaluates each file.

Quality Criteria:
- Completeness: Is the file complete or a fragment?
- Relevance: How related to Evony is the content?
- Uniqueness: Is this duplicate/near-duplicate content?
- Training Value: Would this help an AI understand Evony?
- Noise Level: How much junk/garbage is mixed in?
"""

import os
import json
import hashlib
import re
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Set, Tuple, Optional
from collections import defaultdict
from dataclasses import dataclass, asdict, field
from enum import Enum

from .config import HUB_ROOT, EVONY_KEYWORDS


class QualityRating(Enum):
    """Quality rating for training data."""
    EXCELLENT = 5   # Perfect for training
    GOOD = 4        # Good quality, include
    ACCEPTABLE = 3  # Usable with minor issues
    POOR = 2        # Low quality, needs review
    JUNK = 1        # Do not include


class ContentType(Enum):
    """Type of content for categorization."""
    SOURCE_CODE = "source_code"
    DOCUMENTATION = "documentation"
    PROTOCOL = "protocol"
    EXPLOIT = "exploit"
    SCRIPT = "script"
    GAME_DATA = "game_data"
    KEYS = "keys"
    TOOL = "tool"
    PERSONAL_NOTE = "personal_note"
    JUNK = "junk"
    UNKNOWN = "unknown"


@dataclass
class FileEvaluation:
    """Evaluation result for a single file."""
    path: str
    filename: str
    size: int
    content_hash: str
    content_type: str
    quality_score: int
    quality_rating: str
    relevance_score: float
    completeness_score: float
    noise_score: float
    training_value: float
    
    # Flags
    is_duplicate: bool = False
    is_fragment: bool = False
    is_personal_note: bool = False
    is_junk: bool = False
    include_in_dataset: bool = False
    
    # Details
    keywords_found: List[str] = field(default_factory=list)
    issues: List[str] = field(default_factory=list)
    preview: str = ""
    
    def to_dict(self) -> dict:
        return asdict(self)


# Patterns that indicate JUNK content (do not train on)
JUNK_PATTERNS = [
    # Personal notes and todos
    r'^(todo|fixme|hack|xxx|note to self)',
    r'^#+ (todo|notes?|ideas?)\s*$',
    r'(remember to|don\'t forget|need to)',
    
    # Incomplete/placeholder content
    r'^(test|testing|asdf|qwerty|lorem ipsum)',
    r'(placeholder|coming soon|tbd|wip|work in progress)',
    r'^#+\s*$',  # Empty headers
    
    # Debug/temp output
    r'^(debug|console\.log|print\(|echo )',
    r'(temporary|temp file|delete me|remove this)',
    
    # Generic/boilerplate
    r'^(untitled|new document|copy of)',
    r'(generated by|auto-generated|do not edit)',
    
    # Broken/corrupt
    r'[\x00-\x08\x0b\x0c\x0e-\x1f]{3,}',  # Control characters
    r'^[^\w\s]{10,}',  # Garbage characters
]

# Patterns that indicate LOW QUALITY
LOW_QUALITY_PATTERNS = [
    r'^\s{0,5}.{0,20}$',  # Very short lines only
    r'^[\s\n]*$',  # Empty or whitespace only
    r'(error|exception|traceback|stack trace)',  # Error dumps
    r'[a-f0-9]{32,}',  # Long hex dumps without context
]

# Patterns that indicate HIGH QUALITY Evony content
HIGH_QUALITY_PATTERNS = [
    # Protocol documentation
    r'(amf|action message format|protocol|packet structure)',
    r'(command|request|response|payload)',
    
    # Game mechanics
    r'(troop|army|castle|city|resource|building)',
    r'(attack|defend|reinforce|scout|transport)',
    r'(hero|mayor|prestige|medal|alliance)',
    
    # Technical implementation
    r'(class |def |function |public |private )',
    r'(import |from |require|include)',
    r'(socket|connection|encrypt|decrypt|hash)',
    
    # Exploits/glitches
    r'(glitch|exploit|overflow|bypass|vulnerability)',
    r'(integer overflow|commission|transfer)',
    
    # Keys/secrets
    r'(action_key|api_key|xor_key|salt|secret)',
    r'md5|sha[0-9]+|base64',
]

# Files/patterns to ALWAYS EXCLUDE
ALWAYS_EXCLUDE = {
    # Generic files
    'license.txt', 'license.md', 'license',
    'changelog.md', 'changelog.txt', 'history.md',
    'contributing.md', 'code_of_conduct.md',
    'package.json', 'package-lock.json', 'yarn.lock',
    'tsconfig.json', 'webpack.config.js', '.gitignore',
    '.npmrc', '.editorconfig', '.prettierrc',
    
    # User junk patterns
    'test.txt', 'test.py', 'temp.txt', 'notes.txt',
    'scratch.py', 'scratch.txt', 'draft.md',
    'untitled.txt', 'new.txt', 'copy.txt',
}

# Directories to ALWAYS SKIP
ALWAYS_SKIP_DIRS = {
    'node_modules', '__pycache__', '.git', '.venv', 'venv',
    'Electron_Browser', 'Macromedia', 'TorData',
    'oh-my-logo', 'ASCII_Art_makers', '.idea', '.vscode',
    'dist', 'build', '__MACOSX', 'Proxifier',
}


class EvonyDataCurator:
    """Professional data curation with quality control."""
    
    def __init__(self, source_path: Path = HUB_ROOT):
        self.source_path = source_path
        self.evaluations: Dict[str, FileEvaluation] = {}
        self.content_hashes: Dict[str, List[str]] = defaultdict(list)
        
        # Stats
        self.stats = {
            'total_scanned': 0,
            'skipped': 0,
            'evaluated': 0,
            'by_quality': {r.name: 0 for r in QualityRating},
            'by_type': {t.value: 0 for t in ContentType},
            'approved': 0,
            'rejected': 0,
        }
    
    def _should_skip_path(self, path: Path) -> bool:
        """Check if path should be skipped entirely."""
        path_str = str(path).lower()
        
        for skip_dir in ALWAYS_SKIP_DIRS:
            if skip_dir.lower() in path_str:
                return True
        
        if path.name.lower() in ALWAYS_EXCLUDE:
            return True
        
        return False
    
    def _read_file(self, path: Path) -> Optional[str]:
        """Read file safely with encoding detection."""
        if path.stat().st_size > 500000:
            return None
        
        for encoding in ['utf-8', 'latin-1', 'cp1252']:
            try:
                with open(path, 'r', encoding=encoding, errors='strict') as f:
                    content = f.read()
                    if '\x00' in content[:1000]:
                        return None
                    return content
            except (UnicodeDecodeError, UnicodeError):
                continue
        return None
    
    def _compute_hash(self, content: str) -> str:
        """Compute content hash for deduplication."""
        normalized = re.sub(r'\s+', ' ', content.strip())
        return hashlib.md5(normalized.encode('utf-8', errors='replace')).hexdigest()
    
    def _check_junk_patterns(self, content: str) -> List[str]:
        """Check for junk patterns, return list of issues found."""
        issues = []
        content_lower = content.lower()[:5000]
        
        for pattern in JUNK_PATTERNS:
            if re.search(pattern, content_lower, re.MULTILINE | re.IGNORECASE):
                issues.append(f"Junk pattern: {pattern[:30]}")
        
        return issues
    
    def _check_quality_patterns(self, content: str) -> Tuple[float, List[str]]:
        """Check quality patterns, return score and issues."""
        content_lower = content.lower()
        issues = []
        
        # Check for low quality indicators
        low_quality_count = 0
        for pattern in LOW_QUALITY_PATTERNS:
            if re.search(pattern, content_lower, re.MULTILINE):
                low_quality_count += 1
        
        # Check for high quality indicators
        high_quality_count = 0
        for pattern in HIGH_QUALITY_PATTERNS:
            if re.search(pattern, content_lower):
                high_quality_count += 1
        
        # Calculate quality score (0.0 to 1.0)
        if low_quality_count > 3:
            issues.append("Multiple low-quality indicators found")
        
        quality = min(1.0, max(0.0, 
            0.5 + (high_quality_count * 0.1) - (low_quality_count * 0.15)
        ))
        
        return quality, issues
    
    def _calculate_relevance(self, path: Path, content: str) -> Tuple[float, List[str]]:
        """Calculate Evony relevance score (0.0 to 1.0)."""
        path_lower = str(path).lower()
        content_lower = content.lower()[:10000]
        
        keywords_found = []
        
        for keyword in EVONY_KEYWORDS:
            if keyword in path_lower or keyword in content_lower:
                keywords_found.append(keyword)
        
        # Check for Evony-specific code patterns
        evony_code_patterns = [
            'troop.', 'army.', 'shop.', 'quest.', 'common.',
            'castle.', 'interior.', 'hero.', 'action_key',
        ]
        for pattern in evony_code_patterns:
            if pattern in content_lower and pattern not in keywords_found:
                keywords_found.append(pattern)
        
        # Score based on keyword density
        relevance = min(1.0, len(keywords_found) * 0.15)
        
        return relevance, keywords_found
    
    def _calculate_completeness(self, content: str, path: Path) -> Tuple[float, List[str]]:
        """Check if content appears complete or is a fragment."""
        issues = []
        
        lines = content.split('\n')
        non_empty_lines = [l for l in lines if l.strip()]
        
        # Very short files are likely fragments
        if len(non_empty_lines) < 5:
            issues.append("Very short file (< 5 lines)")
            return 0.3, issues
        
        # Check for common incomplete patterns
        ext = path.suffix.lower()
        
        if ext == '.py':
            # Python: check for proper structure
            if 'def ' not in content and 'class ' not in content:
                if len(non_empty_lines) > 10:
                    issues.append("Python file without functions/classes")
                    return 0.5, issues
        
        if ext == '.as':
            # ActionScript: check for class/package
            if 'package' not in content.lower() and 'class' not in content.lower():
                if len(non_empty_lines) > 10:
                    issues.append("AS file without package/class")
                    return 0.5, issues
        
        if ext == '.md':
            # Markdown: check for headers
            if not re.search(r'^#+\s+\w', content, re.MULTILINE):
                issues.append("Markdown without proper headers")
                return 0.6, issues
        
        # Check for abrupt endings
        last_lines = '\n'.join(lines[-5:]).lower()
        if any(x in last_lines for x in ['todo', 'continue', 'more to come', '...']):
            issues.append("File appears incomplete (ends with TODO/...)")
            return 0.5, issues
        
        return 1.0, issues
    
    def _detect_personal_notes(self, content: str, path: Path) -> bool:
        """Detect if file is personal notes rather than documentation."""
        content_lower = content.lower()[:3000]
        path_lower = str(path).lower()
        
        # Path indicators
        note_paths = ['notes', 'personal', 'scratch', 'draft', 'ideas', 'todo']
        if any(n in path_lower for n in note_paths):
            return True
        
        # Content indicators
        personal_patterns = [
            r'\bi\s+(think|need|want|should|must)\b',
            r'\b(my|mine|myself)\b.*\b(idea|thought|plan)\b',
            r'(remind me|don\'t forget|remember to)',
            r'^[\-\*]\s*(todo|fix|check|ask|look)',
            r'(meeting|call|email|talk to)',
        ]
        
        matches = 0
        for pattern in personal_patterns:
            if re.search(pattern, content_lower, re.MULTILINE):
                matches += 1
        
        return matches >= 2
    
    def _determine_content_type(self, path: Path, content: str) -> ContentType:
        """Determine the content type for categorization."""
        ext = path.suffix.lower()
        path_lower = str(path).lower()
        content_lower = content.lower()[:5000]
        
        # Check for personal notes first
        if self._detect_personal_notes(content, path):
            return ContentType.PERSONAL_NOTE
        
        # Source code
        if ext in ['.as', '.py', '.js', '.ts']:
            if 'class ' in content or 'def ' in content or 'function' in content:
                return ContentType.SOURCE_CODE
        
        # Protocol documentation
        if any(x in content_lower for x in ['amf', 'protocol', 'packet', 'command']):
            if any(x in content_lower for x in ['request', 'response', 'structure']):
                return ContentType.PROTOCOL
        
        # Exploits
        if any(x in path_lower for x in ['exploit', 'glitch', 'hack', 'overflow']):
            return ContentType.EXPLOIT
        if any(x in content_lower for x in ['overflow', 'exploit', 'vulnerability']):
            return ContentType.EXPLOIT
        
        # Scripts (bot scripts)
        if ext == '.txt' and any(x in path_lower for x in ['script', 'attack', 'farm']):
            return ContentType.SCRIPT
        
        # Keys/encryption
        if any(x in path_lower for x in ['key', 'encrypt', 'decrypt', 'secret']):
            return ContentType.KEYS
        
        # Game data
        if ext in ['.json', '.xml', '.csv']:
            return ContentType.GAME_DATA
        
        # Documentation
        if ext == '.md':
            return ContentType.DOCUMENTATION
        
        # Tools
        if any(x in path_lower for x in ['tool', 'analyzer', 'extractor', 'scanner']):
            return ContentType.TOOL
        
        return ContentType.UNKNOWN
    
    def _calculate_training_value(self, eval: FileEvaluation) -> float:
        """Calculate overall training value (0.0 to 1.0)."""
        # Weights for different factors
        weights = {
            'relevance': 0.35,
            'completeness': 0.25,
            'quality': 0.25,
            'noise': 0.15,
        }
        
        # Penalties
        penalties = 0.0
        if eval.is_duplicate:
            penalties += 0.5
        if eval.is_fragment:
            penalties += 0.3
        if eval.is_personal_note:
            penalties += 0.4
        if eval.is_junk:
            penalties += 1.0  # Complete exclusion
        
        # Calculate weighted score
        score = (
            eval.relevance_score * weights['relevance'] +
            eval.completeness_score * weights['completeness'] +
            (eval.quality_score / 5.0) * weights['quality'] +
            (1.0 - eval.noise_score) * weights['noise']
        )
        
        return max(0.0, min(1.0, score - penalties))
    
    def _determine_quality_rating(self, eval: FileEvaluation) -> QualityRating:
        """Determine quality rating from evaluation."""
        if eval.is_junk or eval.training_value < 0.2:
            return QualityRating.JUNK
        if eval.training_value < 0.4:
            return QualityRating.POOR
        if eval.training_value < 0.6:
            return QualityRating.ACCEPTABLE
        if eval.training_value < 0.8:
            return QualityRating.GOOD
        return QualityRating.EXCELLENT
    
    def evaluate_file(self, path: Path) -> Optional[FileEvaluation]:
        """Evaluate a single file for training quality."""
        if not path.is_file():
            return None
        
        if self._should_skip_path(path):
            self.stats['skipped'] += 1
            return None
        
        content = self._read_file(path)
        if content is None:
            self.stats['skipped'] += 1
            return None
        
        if len(content.strip()) < 50:
            self.stats['skipped'] += 1
            return None
        
        self.stats['evaluated'] += 1
        
        # Compute hash for deduplication
        content_hash = self._compute_hash(content)
        is_duplicate = content_hash in self.content_hashes
        self.content_hashes[content_hash].append(str(path))
        
        # Check for junk
        junk_issues = self._check_junk_patterns(content)
        is_junk = len(junk_issues) >= 2
        
        # Calculate quality
        quality_score, quality_issues = self._check_quality_patterns(content)
        
        # Calculate relevance
        relevance, keywords = self._calculate_relevance(path, content)
        
        # Calculate completeness
        completeness, completeness_issues = self._calculate_completeness(content, path)
        is_fragment = completeness < 0.5
        
        # Detect personal notes
        is_personal = self._detect_personal_notes(content, path)
        
        # Determine content type
        content_type = self._determine_content_type(path, content)
        
        # Calculate noise score (0 = clean, 1 = noisy)
        noise_score = min(1.0, (len(junk_issues) + len(quality_issues)) * 0.2)
        
        # Create evaluation
        all_issues = junk_issues + quality_issues + completeness_issues
        
        eval = FileEvaluation(
            path=str(path.relative_to(self.source_path)),
            filename=path.name,
            size=len(content),
            content_hash=content_hash,
            content_type=content_type.value,
            quality_score=int(quality_score * 5),
            quality_rating="",  # Set below
            relevance_score=relevance,
            completeness_score=completeness,
            noise_score=noise_score,
            training_value=0.0,  # Set below
            is_duplicate=is_duplicate,
            is_fragment=is_fragment,
            is_personal_note=is_personal,
            is_junk=is_junk,
            keywords_found=keywords,
            issues=all_issues,
            preview=content[:300].replace('\n', ' '),
        )
        
        # Calculate training value
        eval.training_value = self._calculate_training_value(eval)
        
        # Determine rating
        rating = self._determine_quality_rating(eval)
        eval.quality_rating = rating.name
        eval.quality_score = rating.value
        
        # Determine if should be included
        eval.include_in_dataset = (
            rating.value >= QualityRating.ACCEPTABLE.value and
            not is_duplicate and
            not is_junk and
            relevance >= 0.15
        )
        
        # Update stats
        self.stats['by_quality'][rating.name] += 1
        self.stats['by_type'][content_type.value] += 1
        if eval.include_in_dataset:
            self.stats['approved'] += 1
        else:
            self.stats['rejected'] += 1
        
        self.evaluations[str(path)] = eval
        return eval
    
    def scan_and_evaluate(self, extensions: Set[str] = None):
        """Scan all files and evaluate them."""
        if extensions is None:
            extensions = {'.as', '.py', '.md', '.txt', '.json', '.xml', '.bat', '.ps1'}
        
        print("\n" + "="*60)
        print("EVONY DATA CURATOR - QUALITY ANALYSIS")
        print("="*60)
        print(f"Source: {self.source_path}")
        print(f"Extensions: {extensions}")
        
        file_count = 0
        for path in self.source_path.rglob('*'):
            if not path.is_file():
                continue
            
            if path.suffix.lower() not in extensions:
                continue
            
            self.stats['total_scanned'] += 1
            file_count += 1
            
            if file_count % 1000 == 0:
                print(f"  Evaluated {file_count} files...")
            
            self.evaluate_file(path)
        
        print(f"\nEvaluation complete: {self.stats['evaluated']} files")
    
    def generate_review_report(self, output_path: Path = None) -> Path:
        """Generate detailed review report for human approval."""
        if output_path is None:
            output_path = self.source_path / "DATA_CURATION_REPORT.md"
        
        # Sort evaluations by training value
        sorted_evals = sorted(
            self.evaluations.values(),
            key=lambda e: (-e.training_value, e.path)
        )
        
        # Group by quality rating
        by_rating = defaultdict(list)
        for eval in sorted_evals:
            by_rating[eval.quality_rating].append(eval)
        
        # Generate report
        report = f"""# Evony Data Curation Report

Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Summary

| Metric | Count |
|--------|-------|
| Total Scanned | {self.stats['total_scanned']:,} |
| Evaluated | {self.stats['evaluated']:,} |
| Skipped | {self.stats['skipped']:,} |
| **Approved for Training** | **{self.stats['approved']:,}** |
| Rejected | {self.stats['rejected']:,} |

## Quality Distribution

| Rating | Count | Description |
|--------|-------|-------------|
| EXCELLENT | {self.stats['by_quality']['EXCELLENT']:,} | Perfect for training |
| GOOD | {self.stats['by_quality']['GOOD']:,} | Good quality, include |
| ACCEPTABLE | {self.stats['by_quality']['ACCEPTABLE']:,} | Usable with minor issues |
| POOR | {self.stats['by_quality']['POOR']:,} | Low quality, needs review |
| JUNK | {self.stats['by_quality']['JUNK']:,} | Do not include |

## Content Types

| Type | Count |
|------|-------|
"""
        for ctype, count in sorted(self.stats['by_type'].items(), key=lambda x: -x[1]):
            if count > 0:
                report += f"| {ctype} | {count:,} |\n"
        
        report += """

---

## Files Approved for Training

These files passed quality checks and are recommended for the training dataset:

"""
        approved = [e for e in sorted_evals if e.include_in_dataset]
        for eval in approved[:100]:
            report += f"### ✅ `{eval.filename}`\n"
            report += f"- **Path**: `{eval.path}`\n"
            report += f"- **Type**: {eval.content_type}\n"
            report += f"- **Training Value**: {eval.training_value:.2f}\n"
            report += f"- **Keywords**: {', '.join(eval.keywords_found[:5])}\n"
            if eval.preview:
                report += f"- **Preview**: {eval.preview[:150]}...\n"
            report += "\n"
        
        if len(approved) > 100:
            report += f"\n*...and {len(approved) - 100} more approved files*\n"
        
        report += """

---

## Files REJECTED (Do Not Train)

These files were rejected due to quality issues:

"""
        rejected = [e for e in sorted_evals if not e.include_in_dataset][:50]
        for eval in rejected:
            report += f"### ❌ `{eval.filename}`\n"
            report += f"- **Path**: `{eval.path}`\n"
            report += f"- **Rating**: {eval.quality_rating}\n"
            report += f"- **Issues**: {', '.join(eval.issues[:3]) if eval.issues else 'Low relevance'}\n"
            flags = []
            if eval.is_duplicate:
                flags.append("DUPLICATE")
            if eval.is_junk:
                flags.append("JUNK")
            if eval.is_personal_note:
                flags.append("PERSONAL_NOTE")
            if eval.is_fragment:
                flags.append("FRAGMENT")
            if flags:
                report += f"- **Flags**: {', '.join(flags)}\n"
            report += "\n"
        
        report += """

---

## Duplicate Files Report

Files with identical content (only first occurrence kept):

"""
        duplicates = [(h, paths) for h, paths in self.content_hashes.items() if len(paths) > 1]
        duplicates.sort(key=lambda x: -len(x[1]))
        
        for hash_val, paths in duplicates[:30]:
            report += f"### {len(paths)} copies\n"
            for p in paths[:5]:
                report += f"- `{Path(p).name}`\n"
            if len(paths) > 5:
                report += f"- *...and {len(paths) - 5} more*\n"
            report += "\n"
        
        report += """

---

## Next Steps

1. **Review this report** - Check the approved/rejected files
2. **Override decisions** - Edit the JSON config to include/exclude specific files
3. **Run dataset builder** - Execute with approved files only
4. **Convert to training format** - Generate instruction/response pairs
"""
        
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(report)
        
        # Also save JSON for programmatic access
        json_path = output_path.with_suffix('.json')
        with open(json_path, 'w', encoding='utf-8') as f:
            json.dump({
                'stats': self.stats,
                'approved': [e.to_dict() for e in sorted_evals if e.include_in_dataset],
                'rejected': [e.to_dict() for e in sorted_evals if not e.include_in_dataset],
            }, f, indent=2)
        
        print(f"\nReport saved: {output_path}")
        print(f"JSON data: {json_path}")
        
        return output_path
    
    def print_summary(self):
        """Print curation summary."""
        print("\n" + "="*60)
        print("CURATION SUMMARY")
        print("="*60)
        print(f"\nTotal scanned: {self.stats['total_scanned']:,}")
        print(f"Evaluated: {self.stats['evaluated']:,}")
        print(f"Skipped: {self.stats['skipped']:,}")
        print(f"\n✅ Approved for training: {self.stats['approved']:,}")
        print(f"❌ Rejected: {self.stats['rejected']:,}")
        
        print(f"\nBy Quality:")
        for rating in QualityRating:
            count = self.stats['by_quality'][rating.name]
            if count > 0:
                print(f"  {rating.name:12s}: {count:,}")
        
        print(f"\n{'='*60}\n")


def curate_data():
    """Run the data curation process."""
    curator = EvonyDataCurator()
    curator.scan_and_evaluate()
    curator.generate_review_report()
    curator.print_summary()
    return curator


if __name__ == "__main__":
    curate_data()
